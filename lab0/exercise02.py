## prefix removal & suffix removal

words = [
    "dishes",
    "running",
    "nationality",
    "undo",
    "preheat",
]

word1 = words[0]
print(word1[:-2])

word2 = words[1]
print(word2[:-4])

word3 = words[2]
print(word3[:-5])

word4 = words[3]
print(word4[2:])

word5 = words[4]
print(word5[3:])
